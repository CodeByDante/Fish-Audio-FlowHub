/** Generate the transaction-only integration check from the exact runtime SQL.
 * Run: node tests/generate-bootstrap-verification.mjs
 * This file never connects to a server. The emitted SQL uses two guarded schemas
 * and ends with ROLLBACK; no production public table is renamed, dropped or used.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { QUERIES } from '../src/js/cloud-core.js';

const schema = 'voice_vault_bootstrap_verify';
const partialSchema = 'voice_vault_bootstrap_partial_verify';
const libraryId = '10000000-1111-4111-8111-111111111111';
const sourceUrl = new URL('../src/sql/bootstrap.sql', import.meta.url);
const destination = new URL('../database/verify_bootstrap.sql', import.meta.url);
const source = (await readFile(sourceUrl, 'utf8')).trim();

function fixtureBootstrap(namespace) {
  if (source.match(/^BEGIN;$/gm)?.length !== 1 || source.match(/^COMMIT;$/gm)?.length !== 1 || !source.endsWith('COMMIT;')) {
    throw new Error('Unexpected bootstrap transaction shape; review the generator.');
  }
  let sql = source.replace(/^BEGIN;\n/m, '').replace(/\s*COMMIT;$/, '');
  const realtime = sql.match(/DO \$realtime\$[\s\S]*?\$realtime\$;/g);
  if (realtime?.length !== 1) throw new Error('Expected exactly one canonical Realtime block.');
  sql = sql.replace(realtime[0], '-- Realtime publication changes are excluded from this schema-isolated test.');
  // Case-sensitive replacement preserves the PUBLIC role in privilege statements.
  sql = sql.replace(/\bpublic\b/g, namespace);
  if (/\bpublic\b/.test(sql) || /CREATE PUBLICATION|ALTER PUBLICATION/.test(sql)) {
    throw new Error('A production namespace or publication write remains in the fixture.');
  }
  return sql;
}

if (typeof QUERIES.seed !== 'string') throw new Error('Expected the exact runtime QUERIES.seed SQL.');
function seedSql(namespace) {
  const parameters = [libraryId];
  return QUERIES.seed.replace(/\bpublic\b/g, namespace).replace(/\$(\d+)/g, (_, number) => {
    const value = parameters[Number(number) - 1];
    if (value === undefined) throw new Error(`Review the new runtime seed parameter $${number}.`);
    return `'${value.replaceAll("'", "''")}'`;
  }).replace(/;?\s*$/, ';');
}

function snapshotSql(namespace) {
  return `SELECT jsonb_build_object(
    'libraries', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id), '[]'::jsonb) FROM ${namespace}.libraries t),
    'folders', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id), '[]'::jsonb) FROM ${namespace}.folders t),
    'voices', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id), '[]'::jsonb) FROM ${namespace}.voices t),
    'settings', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.owner_id), '[]'::jsonb) FROM ${namespace}.user_settings t)
  ) AS state`;
}

const sql = `-- Generated by tests/generate-bootstrap-verification.mjs from src/sql/bootstrap.sql.
-- Run as postgres with the Management SQL API. Both test schemas are rolled back.
-- The generator excludes Realtime writes and never uses production public tables.
BEGIN;
SET LOCAL lock_timeout = '10s';
DO $fixture_guard$
BEGIN
  IF current_user <> 'postgres' THEN RAISE EXCEPTION 'Run this administrator test as postgres'; END IF;
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname IN ('${schema}', '${partialSchema}')) THEN
    RAISE EXCEPTION 'Bootstrap test schema already exists; refusing to modify it';
  END IF;
END
$fixture_guard$;
CREATE SCHEMA ${schema};
CREATE SCHEMA ${partialSchema};

-- Exact runtime bootstrap, redirected to an empty isolated schema.
${fixtureBootstrap(schema)}
${seedSql(schema)}
DO $check_empty$
DECLARE snapshot jsonb;
BEGIN
  IF (SELECT count(*) FROM pg_tables WHERE schemaname = '${schema}' AND tablename IN ('libraries','folders','voices','user_settings')) <> 4 THEN
    RAISE EXCEPTION 'Empty bootstrap did not create all four tables';
  END IF;
  IF to_regprocedure('${schema}.vault_export_snapshot(uuid)') IS NULL
     OR to_regprocedure('${schema}.vault_apply_snapshot(uuid,bigint,jsonb)') IS NULL THEN
    RAISE EXCEPTION 'Empty bootstrap did not create both administrator RPCs';
  END IF;
  snapshot := ${schema}.vault_export_snapshot('${libraryId}'::uuid);
  IF snapshot->>'libraryId' IS DISTINCT FROM '${libraryId}'
     OR jsonb_array_length(snapshot->'folders') IS DISTINCT FROM 3
     OR snapshot->'voices' IS DISTINCT FROM '[]'::jsonb
     OR (SELECT owner_id IS NULL FROM ${schema}.libraries WHERE id = '${libraryId}') IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'Default personal library and navigation-folder seed failed';
  END IF;
END
$check_empty$;

-- Populate edited content so reuse must preserve rows, metadata and revisions.
INSERT INTO ${schema}.folders (library_id,id,name,kind,sort_order,metadata)
VALUES ('${libraryId}', 'edited-folder', 'My edited folder', 'custom', 3, '{"fixture":true}');
INSERT INTO ${schema}.voices (library_id,id,title,url,folder_id,is_favorite,notes,metadata)
VALUES ('${libraryId}', 'edited-voice', 'My edited voice', 'https://fish.audio/m/bootstrap-fixture/', 'edited-folder', true, 'Keep this note', '{"unknownField":"keep"}');
UPDATE ${schema}.libraries SET name = 'My edited library', metadata = metadata || '{"unknownLibraryField":"keep"}'::jsonb
WHERE id = '${libraryId}';
CREATE TEMP TABLE vault_bootstrap_expected_state AS ${snapshotSql(schema)};

-- Exact same bootstrap and seed must now take the non-mutating reuse path.
${fixtureBootstrap(schema)}
${seedSql(schema)}
DO $check_reuse$
DECLARE actual jsonb; expected jsonb;
BEGIN
  ${snapshotSql(schema)} INTO actual;
  SELECT state INTO expected FROM vault_bootstrap_expected_state;
  IF actual IS DISTINCT FROM expected THEN
    RAISE EXCEPTION 'Repeated bootstrap or library seed changed existing rows, metadata or revisions';
  END IF;
END
$check_reuse$;

-- A second namespace holds a deliberately partial, incompatible schema.
CREATE TABLE ${partialSchema}.libraries (id uuid PRIMARY KEY, marker text NOT NULL);
INSERT INTO ${partialSchema}.libraries VALUES ('${libraryId}', 'must remain untouched');
DO $check_partial$
DECLARE rejected boolean := false; message text;
BEGIN
  BEGIN
    EXECUTE $partial_bootstrap_sql$
${fixtureBootstrap(partialSchema)}
    $partial_bootstrap_sql$;
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS message = MESSAGE_TEXT;
    IF position('VAULT_SCHEMA_INCOMPATIBLE' IN message) = 0 THEN RAISE; END IF;
    rejected := true;
  END;
  IF NOT rejected
     OR (SELECT count(*) FROM pg_tables WHERE schemaname = '${partialSchema}') <> 1
     OR (SELECT marker FROM ${partialSchema}.libraries WHERE id = '${libraryId}') IS DISTINCT FROM 'must remain untouched'
     OR EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = '${partialSchema}') THEN
    RAISE EXCEPTION 'Partial schema was accepted or changed';
  END IF;
END
$check_partial$;
SELECT 'PASS: empty bootstrap, default library/folders, unchanged repeated reuse, partial-schema rejection, isolated schemas, no Realtime changes' AS result;
ROLLBACK;
`;

await writeFile(destination, sql);
process.stdout.write(`Generated ${fileURLToPath(destination)}\n`);
